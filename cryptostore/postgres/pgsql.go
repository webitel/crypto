// isNotDeployed reports whether err is Postgres' undefined_table (42P01) or
// undefined_column (42703). A schema unit whose table — or a managed field whose
// column — does not exist in this database (the owning service is not installed or
// not migrated yet) holds no data, so Usage/Migrate skip it rather than failing the
// whole operation.
func isNotDeployed(err error) bool {
	var pg *pgconn.PgError
	return errors.As(err, &pg) && (pg.Code == "42P01" || pg.Code == "42703")
}

// SQL identifier. Names come from a trusted operator schema, never
// user input, but quoting keeps mixed-case and reserved words safe.
//
// https://www.postgresql.org/docs/18/sql-syntax-lexical.html#SQL-SYNTAX-IDENTIFIERS
//
// SQL identifiers and key words must begin with a letter (a-z, but also letters with diacritical marks and non-Latin letters) or an underscore (_).
// Subsequent characters in an identifier or key word can be letters, underscores, digits (0-9), or dollar signs ($).
// Note that dollar signs are not allowed in identifiers according to the letter of the SQL standard, so their use might render applications less portable.
// The SQL standard will not define a key word that contains digits or starts or ends with an underscore,
// so identifiers of this form are safe against possible conflict with future extensions of the standard.
//
// [part] indicates whether [word] is a part of a composite identifier, e.g.: <schema>.<table>, <table>.<column>
// [true] excludes checking of reserved KEYWORDs:   rel.name  -but-  "name"
func ident(word string, part bool) string {
	// Quick check for canonical encoding.
	n := len(word)
	if n == 0 {
		return `""` // invalid ; quoted
	}
	keyword := !part // Does we need final check it's definitely NOT a KEYWORD ? DEFAULT: true
	// The SQL standard will not define a key word that contains digits or starts or ends with an underscore,
	// so identifiers of this form are safe against possible conflict with future extensions of the standard.
	for i := range n {
		c := word[i]
		switch {
		case '_' == c: // USCORE
			{
				// The SQL standard will not define a key word that starts or ends with an underscore ..
				if (i == 0) || (i == n-1) {
					keyword = false
				}
			}
		case 'a' <= c && c <= 'z': // LOWER
		case 'A' <= c && c <= 'Z': // UPPER
		case '0' <= c && c <= '9': // DIGIT
			{
				// The SQL standard will not define a key word that contains digits ..
				keyword = false
				if i > 0 {
					continue // OK
				}
				// cannot start with DIGIT !
				return quoteIdent(word)
			}
		default: // invalid character for SQL identifier ; quoted
			{
				return quoteIdent(word)
			}
		}
	}
	if keyword && isKeyword(word) {
		return quoteIdent(word)
	}
	return word
}

// quotes SQL identifier. Names come from a trusted operator schema, never
// user input, but quoting keeps mixed-case and reserved words safe.
func quoteIdent(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

// tableName quotes a "schema.table" identifier part by part.
func tableName(rel string) string {
	schema, table, ok := strings.Cut(rel, ".")
	if !ok {
		return ident(rel, false)
	}
	return ident(schema, true) + "." + ident(table, true)
}

// throttle sleeps so that processing n rows respects ratePerSec (0 = unlimited).
func throttle(ctx context.Context, ratePerSec, n int) error {
	if ratePerSec <= 0 {
		return nil
	}
	d := time.Duration(float64(n) / float64(ratePerSec) * float64(time.Second))
	if d <= 0 {
		return nil
	}
	t := time.NewTimer(d)
	defer t.Stop()
	select {
	case <-ctx.Done():
		return ctx.Err()
	case <-t.C:
		return nil
	}
}

func isKeyword(s string) bool {
	_, ok := slices.BinarySearchFunc(
		keywords, strings.ToUpper(s), strings.Compare,
	)
	return ok
}

